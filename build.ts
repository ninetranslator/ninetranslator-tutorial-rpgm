// Builds the tutorial game: a small RPG Maker MV game in Japanese, starring the crowned cat, for
// players to try the translator on.
//
//     npm run build                  the game folder (www/ + package.json), playable in a browser
//     npm run build -- --windows     + Game.exe (NW.js v0.29.4, as RPG Maker MV ships it)
//     npm run build -- --windows --zip   + the zip players download
//
// Output: dist/. The engine is MV's open-source core scripts (MIT, engine/); the pictures are ours
// (assets/, drawn by art/draw.ts); the story and database are game.ts. The zip is the same byte
// for byte wherever it is built (files in name order, one fixed date), so anyone can rebuild it and
// compare its SHA-256 with the release's.

import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { unzipSync, zipSync, type Zippable } from 'fflate';
import { database, GAME_TITLE } from './game.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const DIST = join(HERE, 'dist');
const NAME = 'ninetranslator-tutorial';
const GAME = join(DIST, NAME);
const NWJS = 'v0.29.4';
const NWJS_ZIP = `nwjs-${NWJS}-win-x64.zip`;
const CACHE = join(HERE, '.cache');

const args = new Set(process.argv.slice(2));

rmSync(GAME, { recursive: true, force: true });
const www = join(GAME, 'www');
mkdirSync(join(www, 'data'), { recursive: true });

// The engine, its page and font.
cpSync(join(HERE, 'engine', 'js'), join(www, 'js'), { recursive: true });
cpSync(join(HERE, 'engine', 'fonts'), join(www, 'fonts'), { recursive: true });
writeFileSync(join(www, 'index.html'), readFileSync(join(HERE, 'engine', 'index.html'), 'utf8').replace('<title></title>', `<title>${GAME_TITLE}</title>`));
writeFileSync(join(www, 'js', 'plugins.js'), '// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n];\n');

// Our pictures.
cpSync(join(HERE, 'assets'), www, { recursive: true });

// The database and maps, written the way the editor writes them.
for (const [file, value] of Object.entries(database())) writeFileSync(join(www, 'data', file), JSON.stringify(value));

// NW.js reads this to open www/index.html in a window the size of the game.
writeFileSync(
  join(GAME, 'package.json'),
  JSON.stringify({ name: NAME, main: 'www/index.html', 'js-flags': '--expose-gc', window: { title: GAME_TITLE, toolbar: false, width: 816, height: 624, icon: 'www/icon/icon.png' } }, null, 2),
);
writeFileSync(join(GAME, 'README.txt'), readFileSync(join(HERE, 'README-player.txt'), 'utf8').replace(/\r?\n/g, '\r\n'));
writeFileSync(join(GAME, 'THIRD-PARTY-NOTICES.txt'), readFileSync(join(HERE, 'engine', 'NOTICES.txt'), 'utf8').replace(/\r?\n/g, '\r\n'));

if (args.has('--windows')) {
  const zip = await nwjs();
  const files = unzipSync(new Uint8Array(zip));
  const root = `nwjs-${NWJS}-win-x64/`;
  for (const [path, bytes] of Object.entries(files)) {
    if (!path.startsWith(root) || path.endsWith('/')) continue;
    const out = join(GAME, path.slice(root.length));
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, bytes);
  }
  renameSync(join(GAME, 'nw.exe'), join(GAME, 'Game.exe'));
}

if (args.has('--zip')) {
  // A zip stores local time, so the date is given in local fields: the same bytes in every time zone.
  const mtime = new Date(2026, 10, 1);
  const tree: Zippable = {};
  const walk = (dir: string) => {
    for (const name of readdirSync(dir).sort()) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else tree[`${NAME}/${relative(GAME, full).replaceAll('\\', '/')}`] = [new Uint8Array(readFileSync(full)), { level: /\.(png|woff2?)$/i.test(name) ? 0 : 9, mtime }];
    }
  };
  walk(GAME);
  const zipPath = join(DIST, `${NAME}${args.has('--windows') ? '-windows' : ''}.zip`);
  const zip = zipSync(tree);
  writeFileSync(zipPath, zip);
  console.log(`zip: ${relative(process.cwd(), zipPath)} (${(zip.length / 1048576).toFixed(1)} MB)`);
  console.log(`sha256: ${createHash('sha256').update(zip).digest('hex')}`);
}

console.log(`tutorial game: ${relative(process.cwd(), GAME)}`);

/**
 * NW.js for Windows, downloaded once from dl.nwjs.io into .cache/. dl.nwjs.io publishes no
 * checksum of the Windows zip for releases this old (its SHASUMS256.txt lists only the headers),
 * so the hash of the first download (2026-10-31, over HTTPS) is pinned here and every later copy
 * must match it.
 */
async function nwjs(): Promise<Buffer> {
  const file = join(CACHE, NWJS_ZIP);
  const expected = '806cb45519af60b184ce3a4e0f573b4d64e43d9758e552787a965ac18b821b1b';
  if (!existsSync(file)) {
    console.log(`downloading ${NWJS_ZIP} from dl.nwjs.io …`);
    const res = await fetch(`https://dl.nwjs.io/${NWJS}/${NWJS_ZIP}`);
    if (!res.ok) throw new Error(`dl.nwjs.io answered ${res.status}`);
    mkdirSync(CACHE, { recursive: true });
    writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  const data = readFileSync(file);
  const actual = createHash('sha256').update(data).digest('hex');
  if (actual !== expected) {
    rmSync(file);
    throw new Error(`${NWJS_ZIP}: checksum ${actual} is not the pinned ${expected} — deleted it; check dl.nwjs.io before trusting a new one`);
  }
  return data;
}

